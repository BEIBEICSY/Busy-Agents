import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

test('macOS app sources provide one pinnable menu bar popover', () => {
  const source = fs.readFileSync('macos/AITaskRadar/AITaskRadarApp.swift', 'utf8');
  const plist = fs.readFileSync('macos/AITaskRadar/Info.plist', 'utf8');
  const buildScript = fs.readFileSync('scripts/build-macos-app.sh', 'utf8');

  assert.match(source, /NSStatusBar\.system\.statusItem/);
  assert.match(source, /button\.title = " \\\(model\.actionCount\)! · \\\(model\.runningCount\)"/);
  assert.doesNotMatch(source, /button\.title = " \\\(model\.runningCount\) · \\\(model\.actionCount\)!"/);
  assert.match(source, /https:\/\/f\.kdocs\.cn\/g\/h09CF9me\//);
  assert.match(source, /Text\("反馈"\)/);
  const header = source.slice(source.indexOf('private var header'), source.indexOf('private var syncLabel'));
  const titleAt = header.indexOf('Agents 在忙啥');
  const pinAt = header.indexOf('pinState.toggle()');
  const feedbackAt = header.indexOf('Text("反馈")');
  const refreshAt = header.indexOf('arrow.clockwise');
  assert.ok(titleAt >= 0 && pinAt > titleAt && feedbackAt > pinAt && refreshAt > feedbackAt);
  assert.match(source, /static let textSize: CGFloat = 16/);
  assert.match(source, /static let feedbackSize: CGFloat = 12/);
  assert.match(source, /static let itemSpacing: CGFloat = 5/);
  assert.match(header, /HeaderBarMetrics\.itemSpacing/);
  assert.match(source, /pointingHand/);
  assert.match(header, /Text\("反馈"\)[\s\S]*HeaderBarMetrics\.feedbackSize/);
  assert.match(source, /open\(DashboardLayout\.feedbackFormURL\)/);
  assert.match(source, /这条数据不对我要反馈/);
  assert.match(source, /请在打开的表单中粘贴当前数据的排查日志/);
  assert.match(source, /api\/session-diagnostic/);
  assert.match(source, /NSPasteboard\.general\.setString/);
  assert.match(source, /\.contextMenu/);
  assert.match(source, /MenuBarIcon-64/);
  assert.match(source, /isTemplate = true/);
  assert.match(plist, /<key>CFBundleIconFile<\/key>\s*<string>AppIcon<\/string>/);
  assert.match(plist, /<key>CFBundleDevelopmentRegion<\/key>\s*<string>en<\/string>/);
  assert.match(plist, /<key>CFBundleDisplayName<\/key>\s*<string>Busy Agents<\/string>/);
  assert.match(plist, /<key>CFBundleName<\/key>\s*<string>Busy Agents<\/string>/);
  assert.match(source, /Agents 在忙啥/);
  assert.match(buildScript, /Busy Agents\.app/);
  const readStrings = (file) => {
    const buf = fs.readFileSync(file);
    if (buf[0] === 0xfe && buf[1] === 0xff) return new TextDecoder('utf-16be').decode(buf.subarray(2));
    if (buf[0] === 0xff && buf[1] === 0xfe) return new TextDecoder('utf-16le').decode(buf.subarray(2));
    return buf.toString('utf8');
  };
  assert.match(readStrings('macos/AITaskRadar/en.lproj/InfoPlist.strings'), /Busy Agents/);
  assert.match(readStrings('macos/AITaskRadar/zh-Hans.lproj/InfoPlist.strings'), /Agents 在忙啥/);
  assert.match(readStrings('macos/AITaskRadar/zh_CN.lproj/InfoPlist.strings'), /Agents 在忙啥/);
  assert.match(readStrings('macos/AITaskRadar/zh-Hans-CN.lproj/InfoPlist.strings'), /Agents 在忙啥/);
  assert.match(buildScript, /AppIcon\.iconset/);
  assert.match(buildScript, /iconutil -c icns/);
  assert.doesNotMatch(buildScript, /sips -z/);
  assert.match(buildScript, /MenuBarIcon-64\.png/);
  assert.ok(fs.existsSync('macos/AITaskRadar/Resources/AppIcon-1024.png'));
  assert.ok(fs.existsSync('macos/AITaskRadar/Resources/AppIcon.iconset/icon_16x16.png'));
  assert.ok(fs.existsSync('macos/AITaskRadar/Resources/AppIcon.iconset/icon_512x512@2x.png'));
  assert.ok(fs.existsSync('macos/AITaskRadar/Resources/MenuBarIcon.png'));
  assert.ok(fs.existsSync('macos/AITaskRadar/Resources/MenuBarIcon-64.png'));
  assert.match(source, /NSPopover/);
  assert.doesNotMatch(source, /RadarWindowController|打开独立窗口/);
  assert.match(source, /pin\.fill/);
  assert.match(source, /\.applicationDefined : \.transient/);
  assert.match(source, /api\/sessions/);
  assert.match(source, /api\/actions/);
  assert.match(source, /api\/data-roots/);
  assert.match(source, /connectionSummary/);
  assert.match(source, /已打开 \\\(Self\.openedAppLabel\(for: session\)\)/);
  assert.match(source, /func showOpenedToast/);
  assert.match(source, /hidesOnDeactivate = false/);
  assert.match(source, /expectedBackendSchemaVersion = 2/);
  assert.match(source, /127\.0\.0\.1:4178/);
  assert.match(source, /schemaVersion/);
  assert.ok(source.includes('Text("最近 7 天，共 \\(model.sessions.count) 任务")'));
  assert.match(plist, /<key>LSUIElement<\/key>/);
  assert.match(buildScript, /Contents\/Resources\/backend/);
  assert.match(buildScript, /BUNDLE_NODE/);
  assert.match(buildScript, /fetch-node-runtime\.sh/);
  assert.match(buildScript, /NodeRuntime\.entitlements/);
  const bundledAt = source.indexOf('runtime/bin/node');
  const lookupAt = source.indexOf('NodeLookup.locate');
  assert.ok(bundledAt > 0 && lookupAt > bundledAt);
  assert.match(buildScript, /NodeLookup\.swift/);
  const lookup = fs.readFileSync('macos/AITaskRadar/NodeLookup.swift', 'utf8');
  assert.match(lookup, /Application Support\/fnm/);
  assert.match(lookup, /aliases\/default\/bin\/node/);
  assert.match(lookup, /node-versions/);
  assert.match(lookup, /\.nvm\/alias/);
  assert.match(lookup, /\.asdf\/shims\/node/);
  assert.match(lookup, /\.zshrc/);
  assert.match(lookup, /minimumMajor = 20/);
  assert.match(source, /startupError/);
  const runtime = fs.readFileSync('scripts/fetch-node-runtime.sh', 'utf8');
  assert.match(runtime, /NODE_VERSION="22\.22\.3"/);
  assert.match(runtime, /0da7ff74ef8611328c8212f17943368713a2ad953fb7d89a8c8a0eae87c23207/);
  assert.match(runtime, /45830ba752fa0d892c6dcd640946669801293cac820a33591ded40ac075198ec/);
  assert.match(
    fs.readFileSync('macos/AITaskRadar/NodeRuntime.entitlements', 'utf8'),
    /com\.apple\.security\.cs\.allow-jit/
  );
});
